"""Order the translated functions in the GameCube's paged code by how often they run.

The pager brings code in 4 KB pages, from the disc in 64 KB blocks (docs/gamecube.md, "Code").
Functions laid out in address order put the code a frame runs on hundreds of pages; ordered by
their call counts in a PGO profile (the PC's, docs/recompiler.md), the hottest code shares a few
pages and stays resident, and what a boot or a load runs comes in sequential blocks.

  "C:/Program Files/LLVM/bin/llvm-profdata" show --all-functions build/pgo_pc2/nova3.profdata > prof.txt
  python tools/gc_order.py prof.txt build/gc/cmake/gcode_order.ld

The output is a list of input-section rules for the .gcode output section (tools/gc/ld/ogc.ld
INCLUDEs it): functions that ran, by call count (most first); the others follow in the default
rule. GCC's -ffunction-sections names a function's section .text.<name>.
"""
import re, sys


def main():
    prof, out = sys.argv[1], sys.argv[2]
    counts, cur = {}, None
    for line in open(prof, encoding='utf-8', errors='replace'):
        m = re.match(r'  ([ft]_[0-9a-f]{8}):', line)
        if m:
            cur = m.group(1)
            continue
        if line.startswith('  ') and not line.startswith('    '):
            cur = None
            continue
        m = re.match(r'\s+Function count: (\d+)', line)
        if m and cur:
            counts[cur] = int(m.group(1))
    ran = sorted((n for n, c in counts.items() if c > 0), key=lambda n: -counts[n])
    with open(out, 'w') as f:
        f.write('/* generated by tools/gc_order.py: functions by PGO call count, most first */\n')
        for n in ran:
            # the function and GCC's clones of it (constprop, isra, part)
            f.write(f'*code_*(.text.{n} .text.{n}.*)\n')
    print(f'{out}: {len(ran)} of {len(counts)} functions ordered')


if __name__ == '__main__':
    main()
